#!/usr/bin/env node
/**
 * Writes sample screenshot pairs for the Two Screen Comparison tab to public/test-screenshots/.
 * They are synthetic (drawn by tests/helpers/synthetic-screens.js), contain no real data, and each pair exercises
 * one acceptance case. Run: node scripts/make-test-screenshots.js
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');
const { drawScreen } = require('../tests/helpers/synthetic-screens');

const out = path.join(__dirname, '..', 'public', 'test-screenshots');
fs.mkdirSync(out, { recursive: true });

(async () => {
  const files = {
    'prod-reference.png': drawScreen(),
    'dev-identical.png': drawScreen(),
    'dev-several-changes.png': drawScreen({ buttonColor: [16, 185, 129], iconPresent: false, valueSeed: 99, titleShiftX: 6 }),
    'dev-clock-changed.png': drawScreen({ clockSeed: 42 }),
    'dev-disabled-button.png': drawScreen({ buttonDisabled: true }),
    'dev-taller.png': drawScreen({ height: 400 }),
    'prod-reference-2x.png': await sharp(drawScreen()).resize(960, 640, { kernel: 'nearest' }).png().toBuffer(),
    'not-an-image.png': Buffer.from('This file is text with a .png name, to test the invalid-image error.\n'),
  };
  for (const [name, buf] of Object.entries(files)) fs.writeFileSync(path.join(out, name), buf);
  fs.writeFileSync(
    path.join(out, 'README.md'),
    `# Two Screen Comparison sample screenshots

Synthetic images (no real data), generated by \`node scripts/make-test-screenshots.js\`.
Use **prod-reference.png** as PROD and one of these as DEV:

| DEV file | Expect |
|---|---|
| dev-identical.png | "No material differences within tolerance" |
| dev-several-changes.png | 4 findings: title moved (layout), button color, icon missing in DEV, table value changed (text) |
| dev-clock-changed.png | 1 finding in the header clock; draw an ignore region over the clock (top-right) and it is excluded + logged |
| dev-disabled-button.png | State finding: button looks disabled in DEV |
| dev-taller.png | Different dimensions warning; choose an alignment (top-left reports the extra 80px) |

Also: PROD = prod-reference-2x.png with DEV = dev-identical.png → device-pixel-ratio warning, use "Scale PROD to DEV".
DEV or PROD = not-an-image.png → "Invalid image" error.

These images contain no real text, so they exercise the pixel checks (tick the visual categories). For the data-first
checks (Data & Text with OCR) use the browser-rendered dashboards in **data/** (see data/README.md).
`
  );
  console.log(`Wrote ${Object.keys(files).length} files to ${out}`);
})();
